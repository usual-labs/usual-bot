import Foundation
import Testing

@testable import HermesKit

/// Hermes stores turns it starts itself as user messages. These must not read as yours.
struct GatewayTurnTests {
    private static let footer = """
        [INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. \
        Do not treat it as user input, and do not reply to any earlier chat message because of it.]
        """
    private static let notice = """
        [IMPORTANT: Background process proc_a completed normally (exit code 0).
        Command: ./verify.sh
        Output:
        [... output truncated — showing last 0 chars]
        ]

        \(footer)
        """
    private static let report = "Command: ./verify.sh\nOutput:\n[... output truncated — showing last 0 chars]"

    private func contents(_ history: [HistoryMessage]) -> [TranscriptItem.Content] {
        ThreadState(history: history, running: false).items.map(\.content)
    }

    @Test func aFinishedProcessIsAResultWithHermesTitle() throws {
        // The shape `session.resume` sends.
        let wire: JSONValue = [
            "messages": [
                [
                    "role": "user", "text": .string(Self.notice), "display_kind": "process_complete",
                    "display_metadata": ["display_text": "Background Process Finished: ./verify.sh"],
                ]
            ]
        ]
        let history = try #require(try wire["messages"]?.decode([HistoryMessage].self))

        #expect(contents(history) == [.result(title: "Background Process Finished: ./verify.sh", detail: Self.report)])
    }

    @Test func rowsSavedBeforeHermesTypedThemAreRecognisedByTheirText() {
        #expect(
            contents([HistoryMessage(role: "user", text: Self.notice)]) == [
                .result(title: "Background process proc_a completed normally (exit code 0).", detail: Self.report)
            ])
    }

    @Test func aSubagentFinishingIsAResult() {
        let text = "[ASYNC DELEGATION COMPLETE — d1]\nA background subagent you dispatched earlier has finished."
        #expect(
            contents([HistoryMessage(role: "user", text: text, displayKind: "async_delegation_complete")]) == [
                .result(
                    title: "Background agent work finished",
                    detail: "A background subagent you dispatched earlier has finished.")
            ])
    }

    @Test func anInternalNotificationIsAResult() {
        let text = "Cronjob finished.\n\n\(Self.footer)"
        #expect(
            contents([HistoryMessage(role: "user", text: text, displayKind: "internal_notification")]) == [
                .result(title: "Message from Hermes", detail: "Cronjob finished.")
            ])
    }

    @Test func aResumedTurnIsANotice() {
        let text = "[System note: Your previous turn was interrupted mid-run. Continue.]"
        #expect(
            contents([HistoryMessage(role: "user", text: text, displayKind: "auto_continue")]) == [
                .notice("Picked up an interrupted reply")
            ])
    }

    @Test func yourOwnWordsStayYours() {
        for (text, kind) in [
            ("[IMPORTANT: read this first", nil), ("Background process finished?", nil),
            ("/work fix the leak", "skill_invocation"), ("Hello", "a kind from a newer gateway"),
        ] {
            #expect(contents([HistoryMessage(role: "user", text: text, displayKind: kind)]) == [.user(text)])
        }
    }

    @Test func aRunningNotificationTurnIsntShownAsYours() {
        let state = ThreadState(
            history: [], running: true,
            inflight: InflightTurn(
                user: Self.notice, assistant: "Checking", displayKind: "process_complete", displayText: "Finished"))

        #expect(state.items.map(\.content) == [.result(title: "Finished", detail: Self.report)])
        #expect(state.draft == "Checking")
    }

    @Test func aRunningTurnKeepsItsResultFromHistoryOnce() {
        let row = HistoryMessage(role: "user", text: Self.notice, displayKind: "process_complete", displayText: "Done")
        let state = ThreadState(
            history: [row], running: true,
            inflight: InflightTurn(
                user: Self.notice, assistant: "", displayKind: "process_complete", displayText: "Done"))

        #expect(state.items.count == 1)
    }

    @Test func aLiveTurnThatCarriesACardShowsIt() {
        var state = ThreadState()
        state.apply(
            GatewayEvent(
                type: "message.start", sessionID: "s1", seq: nil,
                payload: [
                    "display_kind": "process_complete", "display_text": "Finished", "text": .string(Self.notice),
                ]))
        state.apply(GatewayEvent(type: "message.start", sessionID: "s1", seq: nil, payload: [:]))

        #expect(state.items.map(\.content) == [.result(title: "Finished", detail: Self.report)])
        #expect(state.isRunning)
    }

    @Test func theSidebarSaysWhatHappened() {
        #expect(Contact.plainPreview(Self.notice) == "Background process finished")
        #expect(Contact.plainPreview("[ASYNC DELEGATION COMPLETE — d1]\nDone") == "Background agent work finished")
        #expect(Contact.plainPreview("[IMPORTANT: read this first") == "[IMPORTANT: read this first")
    }

    @MainActor @Test func undoSkipsWhatYouDidntSend() {
        let state = ThreadState(
            history: [
                HistoryMessage(role: "user", text: "Run it"),
                HistoryMessage(role: "user", text: Self.notice, displayKind: "process_complete"),
            ], running: false)
        let thread = ChatThread(
            contactID: "hermes", cached: CachedThread(state: state, lastViewed: nil, unreadCount: 0), channel: { nil })

        #expect(thread.lastSent?.content == .user("Run it"))
    }
}
