import Foundation
import Testing

@testable import HermesKit

/// Bots messaging each other: the asking Bot's line, the answer that comes back, and the other
/// Bot's chat folding the exchange away. Text and shapes are Hermes 0.23.0's
/// (`tools/bot_mode_dm.py`, `tools/bot_mode_dm_outcome.py`), as a real gateway stored them.
@MainActor
struct BotTalkTests {
    private static let ask = "Message from 🤖 CMO (@cmo): Make the Work Analyst a routine on my profile."
    private static let note = "Message from 🤖 dr eggbot (@dr-eggbot): [no reply needed] The treg test passed."
    private static let footer =
        "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input.]"

    /// What a delivery's background process tells the asking Bot when it ends.
    private static func delivery(output: String, exit: Int = 0, profile: String = "dr-eggbot") -> String {
        """
        [IMPORTANT: Background process proc_e30eb7aaad10 completed normally (exit code \(exit)).
        Command: /opt/python3 /opt/hermes-agent/tools/bot_mode_dm.py --run-delivery --author '{}' \
        --query-file /tmp/dm.txt --profile-home /home/u/.hermes/profiles/\(profile) /opt/hermes -p \(profile)
        Output:
        \(output)
        ]

        \(footer)
        """
    }

    private func content(_ text: String, kind: String = "internal_notification") -> TranscriptItem.Content? {
        GatewayTurn.content(text: text, kind: kind, title: nil)
    }

    // MARK: - Another Bot's message

    @Test func anotherBotsMessageKeepsWhoAndWhetherItWantsAReply() {
        #expect(
            content(Self.ask)
                == .botMessage(from: "CMO", text: "Make the Work Analyst a routine on my profile.", isNote: false))
        #expect(content(Self.note) == .botMessage(from: "dr eggbot", text: "The treg test passed.", isNote: true))
    }

    // MARK: - The answer

    @Test func anAnswerIsReadFromTheDeliverysReport() {
        let output =
            #"Using Node v26.12.1"# + "\n"
            + #"{"outcome": "@dr-eggbot answered.", "reply": "Both routines are on your profile.", "status": "settled", "delivery_id": "1483"}"#
        #expect(
            content(Self.delivery(output: output), kind: "process_complete")
                == .botAnswer([BotAnswer(from: "dr-eggbot", outcome: .answered("Both routines are on your profile."))]))
    }

    /// NousResearch/hermes-agent#152075: a long reply is one line, and Hermes cuts it to nothing.
    @Test func aReplyHermesCutToNothingIsLost() {
        let output = "[… output truncated — showing last 0 chars]"
        #expect(
            content(Self.delivery(output: output), kind: "process_complete")
                == .botAnswer([BotAnswer(from: "dr-eggbot", outcome: .lost)]))
    }

    @Test func noReplyAWaitThatRanOutAndAFailureEachSaySo() {
        let silent = #"{"outcome": "@scout finished its turn without replying.", "status": "settled"}"#
        let pending =
            #"{"outcome": "@scout never answered within the wait: its turn is still running.", "status": "claimed"}"#
        let failed = #"{"outcome": "@scout never answered: x.", "status": "failed", "error": "Scout isn't running."}"#
        func answer(_ output: String, exit: Int = 0) -> BotAnswer.Outcome? {
            guard case .botAnswer(let answers) = content(Self.delivery(output: output, exit: exit, profile: "scout"))
            else { return nil }
            return answers.first?.outcome
        }
        #expect(answer(silent) == .silent)
        #expect(answer(pending) == .pending("@scout never answered within the wait: its turn is still running."))
        #expect(answer(failed, exit: 1) == .failed("Scout isn't running."))
    }

    @Test func severalBotsAnswerInOne() {
        let output = #"""
            {"outcome": "…", "replies": [{"to": "@scout", "status": "settled", "reply": "Green."}, {"to": "@forge", "status": "failed", "error": "Forge isn't running."}], "settled": 1}
            """#
        let report = Self.delivery(output: output).replacingOccurrences(of: "--run-delivery", with: "--fan-out")
        #expect(
            content(report, kind: "process_complete")
                == .botAnswer([
                    BotAnswer(from: "scout", outcome: .answered("Green.")),
                    BotAnswer(from: "forge", outcome: .failed("Forge isn't running.")),
                ]))
    }

    @Test func anyOtherProcessIsStillAResult() {
        let report = Self.delivery(output: "ok").replacingOccurrences(
            of: "bot_mode_dm.py --run-delivery", with: "backup.sh")
        guard case .result = content(report, kind: "process_complete") else {
            Issue.record("not a result")
            return
        }
    }

    // MARK: - The asking Bot's line

    private static func messageAgent(id: String, _ args: JSONValue) -> HistoryMessage {
        HistoryMessage(role: "tool", name: "message_agent", context: "", toolCallId: id, args: args)
    }

    @Test func aMessageToAnotherBotIsALineOfItsOwn() {
        let history = [
            HistoryMessage(role: "user", text: "Ask dr eggbot to move them"),
            HistoryMessage(role: "tool", name: "read_file", context: "SOUL.md", toolCallId: "t1"),
            Self.messageAgent(id: "t2", ["target": "@dr-eggbot", "message": "Make both routines mine."]),
            Self.messageAgent(id: "t3", ["target": "marloes, scout", "message": "FYI", "expects_reply": "false"]),
            HistoryMessage(role: "assistant", text: "I've asked dr eggbot."),
        ]
        let items = ThreadState(history: history, running: false).items.map(\.content)
        #expect(items.count == 5)
        #expect(
            items[2]
                == .botAsk(
                    BotAsk(
                        id: "t2", to: ["dr-eggbot"], message: "Make both routines mine.", wantsReply: true, state: .done
                    )))
        #expect(
            items[3]
                == .botAsk(BotAsk(id: "t3", to: ["marloes", "scout"], message: "FYI", wantsReply: false, state: .done)))
    }

    @Test func aMessageHermesRefusedFailsWithItsReason() {
        var state = ThreadState()
        state.sendLocally("Ask CMO")
        state.apply(
            GatewayEvent(
                type: "tool.start", sessionID: "s", seq: nil,
                payload: [
                    "tool_id": "t1", "name": "message_agent", "args": ["target": "cmo", "message": "Hi"],
                ]))
        guard case .botAsk(let running) = state.items.last?.content else {
            Issue.record("no line")
            return
        }
        #expect(running.state == .running)
        state.apply(
            GatewayEvent(
                type: "tool.complete", sessionID: "s", seq: nil,
                payload: [
                    "tool_id": "t1", "name": "message_agent",
                    "result": #"{"error": "This bot-to-bot exchange already reached its limit of 4 messages."}"#,
                ]))
        guard case .botAsk(let failed) = state.items.last?.content else {
            Issue.record("no line")
            return
        }
        #expect(failed.state == .failed)
        #expect(failed.error == "This bot-to-bot exchange already reached its limit of 4 messages.")
    }

    @Test func aMessageWaitsUntilItsAnswerComesOrHermesStopsWaiting() {
        let now = Date()
        func ask(_ id: String, to: String, sent: TimeInterval, reply: Bool = true) -> TranscriptItem {
            TranscriptItem(
                id: Int(id.dropFirst())!,
                content: .botAsk(BotAsk(id: id, to: [to], message: "", wantsReply: reply, state: .done)),
                date: now.addingTimeInterval(-sent))
        }
        let answer = TranscriptItem(id: 9, content: .botAnswer([BotAnswer(from: "forge", outcome: .lost)]), date: now)
        let items = [
            ask("a1", to: "scout", sent: 60), ask("a2", to: "forge", sent: 60),
            ask("a3", to: "sage", sent: 60, reply: false),
            ask("a4", to: "atlas", sent: 40 * 60), answer,
        ]
        // Forge's answer is Forge's, not the earlier message's; a note and an old one aren't waited on.
        #expect(BotAsk.waiting(in: items, now: now) == ["a1"])
    }

    // MARK: - The other Bot's chat

    private func exchangeChat() -> [TranscriptItem] {
        let history = [
            HistoryMessage(role: "user", text: "Hi", timestamp: 1),
            HistoryMessage(role: "assistant", text: "Hello.", timestamp: 2),
            HistoryMessage(
                role: "user", text: Self.ask + "\n\n" + Self.footer, timestamp: 3, displayKind: "internal_notification"),
            HistoryMessage(role: "tool", name: "terminal", context: "hermes cron list", toolCallId: "t1", timestamp: 4),
            HistoryMessage(role: "tool", name: "write_file", context: "cron.json", toolCallId: "t2", timestamp: 5),
            HistoryMessage(role: "assistant", text: "Both routines are on your profile.", timestamp: 6),
        ]
        return ThreadState(history: history, running: false).items
    }

    @Test func aBotsMessageAndWhatFollowsAreOneExchange() {
        let items = exchangeChat()
        let exchanges = BotExchange.all(in: items)
        #expect(exchanges == [BotExchange(from: "CMO", isNote: false, items: 2..<5)])
        #expect(exchanges.first?.steps(in: items) == 2)
        #expect(BotExchange.last(in: items) == exchanges.first)
        #expect(exchanges.first?.summary(running: false) == "Talked with CMO")
        #expect(exchanges.first?.summary(running: true) == "Working for CMO…")
    }

    @Test func yourNextMessageEndsIt() {
        var state = ThreadState(history: [], running: false)
        state.apply(
            GatewayEvent(
                type: "message.start", sessionID: "s", seq: nil,
                payload: [
                    "display_kind": "internal_notification", "display_text": "Message from CMO",
                    "text": .string(Self.note),
                ]))
        state.apply(GatewayEvent(type: "message.complete", sessionID: "s", seq: nil, payload: ["text": "Noted."]))
        state.sendLocally("What did CMO want?")
        #expect(BotExchange.all(in: state.items).map(\.items) == [0..<2])
        #expect(BotExchange.all(in: state.items).first?.isNote == true)
        #expect(BotExchange.last(in: state.items) == nil)
    }

    @Test func aReplyToABotIsntUnreadOrAnnounced() {
        let thread = ChatThread.sample("forge", state: ThreadState())
        thread.isVisible = false
        var alerts: [AgentAlert] = []
        thread.alert = { alerts.append($0) }
        thread.apply(
            GatewayEvent(
                type: "message.start", sessionID: "sample", seq: nil,
                payload: [
                    "display_kind": "internal_notification", "display_text": "Message from CMO",
                    "text": .string(Self.ask),
                ]))
        thread.apply(GatewayEvent(type: "message.complete", sessionID: "sample", seq: nil, payload: ["text": "Done."]))
        #expect(thread.unreadCount == 0)
        #expect(alerts.isEmpty)
        // Your own message's reply still is.
        thread.apply(GatewayEvent(type: "message.start", sessionID: "sample", seq: nil, payload: [:]))
        thread.apply(GatewayEvent(type: "message.complete", sessionID: "sample", seq: nil, payload: ["text": "Hi."]))
        #expect(thread.unreadCount == 1)
    }

    @Test func historyCountsOnlyRepliesToYou() {
        let history = [
            HistoryMessage(role: "user", text: "Hi"), HistoryMessage(role: "assistant", text: "Hello."),
            HistoryMessage(role: "user", text: Self.ask, displayKind: "internal_notification"),
            HistoryMessage(role: "assistant", text: "Done, CMO."),
            HistoryMessage(role: "user", text: "Thanks"), HistoryMessage(role: "assistant", text: "Any time."),
        ]
        #expect(GatewayTurn.repliesToYou(in: history).compactMap(\.text) == ["Hello.", "Any time."])
    }

    // MARK: - Names

    @Test func aHandleFindsItsBot() {
        var egg = Contact(id: "dr-eggbot", name: "dr eggbot")
        egg.details = AgentDetails(profile: "dr-eggbot", description: nil, model: nil, provider: nil, skillCount: nil)
        let bots = [Contact(id: "default", name: "Hermes"), egg, Contact(id: "work", name: "Dr. Foo")]
        #expect(bots.bot(named: "@dr-eggbot")?.id == "dr-eggbot")
        #expect(bots.bot(named: "hermes")?.id == "default")
        #expect(bots.bot(named: "dr-foo")?.id == "work")
        #expect(bots.botName("creator-analyst") == "Creator Analyst")
        #expect(bots.botName("lab/scout") == "lab/scout")
    }
}
