import Foundation

/// Turns Hermes starts itself. It stores them as user messages so the model reads them, and marks
/// them with a display kind, but nobody typed them.
enum GatewayTurn {
    private static let processPrefix = "[IMPORTANT: Background process "
    private static let delegationPrefix = "[ASYNC DELEGATION"
    /// What Hermes appends for the model. Its reader only needs what happened.
    private static let footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway"
    /// A routine's output delivered into its Bot Chat: `[Cronjob "<name>" output — …]`, a blank
    /// line, then the output (`cron/scheduler_delivery.py`).
    private static let routinePrefix = "[Cronjob \""
    /// Another Bot's message: `Message from 🤖 <name> (@<handle>): <body>` (`tools/bot_mode_dm.py`).
    private static let botPrefix = "Message from 🤖 "

    /// How a user row reads in a chat. Rows saved before Hermes typed them have only their wording
    /// to go on. An unknown kind stays a message, so nothing you wrote can disappear.
    static func content(text: String, kind: String?, title: String?) -> TranscriptItem.Content {
        let body = withoutFooter(text)
        if kind == "process_complete" || body.hasPrefix(processPrefix) {
            let (headline, detail) = firstLine(of: unwrapped(body))
            return .result(title: title ?? headline, detail: detail)
        }
        if kind == "async_delegation_complete" || body.hasPrefix(delegationPrefix) {
            let (_, detail) = firstLine(of: body)
            return .result(title: title ?? agentWorkFinished, detail: detail)
        }
        switch kind {
        case "internal_notification":
            if let (routine, output) = routineResult(body) {
                return .result(title: title ?? fromRoutine(routine), detail: output)
            }
            if let (bot, message) = botMessage(body) {
                return .result(title: title ?? String(localized: "Message from \(bot)"), detail: message)
            }
            return .result(title: title ?? String(localized: "Message from Hermes"), detail: body)
        case "auto_continue":
            return .notice(String(localized: "Picked up an interrupted reply"))
        default:
            return .user(text)
        }
    }

    /// What the sidebar says when one of these is the chat's newest message. The gateway's preview
    /// comes without its kind, and cut short.
    static func preview(of text: String) -> String? {
        if text.hasPrefix(processPrefix) { return String(localized: "Background process finished") }
        if text.hasPrefix(delegationPrefix) { return agentWorkFinished }
        if let (routine, _) = routineResult(text) { return fromRoutine(routine) }
        return nil
    }

    private static func fromRoutine(_ name: String) -> String { String(localized: "From the routine “\(name)”") }

    private static func routineResult(_ text: String) -> (name: String, output: String)? {
        guard text.hasPrefix(routinePrefix) else { return nil }
        let rest = text.dropFirst(routinePrefix.count)
        guard let close = rest.range(of: "\" output — ") else { return nil }
        let output = rest[close.upperBound...].range(of: "]\n\n").map { rest[$0.upperBound...] } ?? ""
        return (String(rest[..<close.lowerBound]), output.trimmingCharacters(in: .whitespacesAndNewlines))
    }

    private static func botMessage(_ text: String) -> (name: String, body: String)? {
        guard text.hasPrefix(botPrefix), let colon = text.range(of: "): ") else { return nil }
        let sender = text[text.index(text.startIndex, offsetBy: botPrefix.count)..<colon.lowerBound]
        // `Name (@handle`: the handle goes; a name can hold brackets of its own.
        guard let handle = sender.range(of: " (@", options: .backwards) else { return nil }
        return (String(sender[..<handle.lowerBound]), String(text[colon.upperBound...]))
    }

    private static var agentWorkFinished: String { String(localized: "A background helper finished") }

    private static func withoutFooter(_ text: String) -> String {
        let kept = text.range(of: footer, options: .backwards).map { String(text[..<$0.lowerBound]) } ?? text
        return kept.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// `[IMPORTANT: …]` without its brackets.
    private static func unwrapped(_ text: String) -> String {
        var body = Substring(text)
        if body.hasPrefix("[IMPORTANT: ") { body = body.dropFirst("[IMPORTANT: ".count) }
        if body.hasSuffix("]") { body = body.dropLast() }
        return body.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private static func firstLine(of text: String) -> (line: String, rest: String) {
        let parts = text.split(separator: "\n", maxSplits: 1, omittingEmptySubsequences: false)
        return (
            parts.first.map(String.init) ?? text,
            parts.count > 1 ? parts[1].trimmingCharacters(in: .whitespacesAndNewlines) : ""
        )
    }
}
